-- Safe per-request telemetry only: no prompts, generated text, user identifiers, or secrets.
create table ai_request_diagnostics (
    id bigint generated by default as identity primary key,
    usage_date date not null,
    operation varchar(32) not null,
    provider varchar(32) not null,
    model varchar(100) not null,
    requested_at timestamp with time zone not null default now(),
    http_status integer,
    provider_error_code varchar(100),
    finish_reason varchar(40),
    prompt_tokens integer not null default 0,
    completion_tokens integer not null default 0,
    total_tokens integer not null default 0,
    json_parsed boolean not null default false,
    schema_valid boolean not null default false,
    outcome varchar(40) not null,
    field_validation_result varchar(80),
    factuality_rejection_reason varchar(40),
    constraint ck_ai_request_diagnostic_tokens check (
        prompt_tokens >= 0 and completion_tokens >= 0 and total_tokens >= 0
    ),
    constraint ck_ai_request_diagnostic_status check (http_status is null or http_status between 100 and 599)
);
create index idx_ai_diagnostic_requested_at on ai_request_diagnostics(requested_at);
create index idx_ai_diagnostic_operation_date on ai_request_diagnostics(operation, usage_date);
