create table user_topic_interests (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users(id) on delete cascade,
    topic varchar(80) not null,
    score double precision not null default 0,
    updated_at timestamp with time zone not null default now(),
    constraint uk_user_topic_interest unique (user_id, topic)
);
create index idx_user_topic_interests_user on user_topic_interests(user_id);

-- Retain a tombstone after guest data is removed so an old cookie cannot replay a merge.
create table guest_migrations (
    guest_id varchar(36) primary key,
    user_id bigint not null references users(id) on delete restrict,
    migrated_at timestamp with time zone not null default now()
);
create index idx_guest_migrations_user on guest_migrations(user_id);
