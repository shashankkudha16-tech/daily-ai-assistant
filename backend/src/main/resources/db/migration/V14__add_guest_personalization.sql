create table guest_article_interactions (
    id bigint generated by default as identity primary key,
    guest_id varchar(36) not null,
    article_id bigint not null references articles(id) on delete cascade,
    open_count integer not null default 0,
    qualified_view_count integer not null default 0,
    opened_at timestamp with time zone,
    qualified_viewed_at timestamp with time zone,
    recommended_at timestamp with time zone,
    constraint uk_guest_article_interaction unique (guest_id, article_id)
);
create index idx_guest_interactions_guest_opened on guest_article_interactions(guest_id, opened_at);

create table guest_topic_interests (
    id bigint generated by default as identity primary key,
    guest_id varchar(36) not null,
    topic varchar(80) not null,
    score double precision not null default 0,
    updated_at timestamp with time zone not null default now(),
    constraint uk_guest_topic_interest unique (guest_id, topic)
);
create index idx_guest_topic_interests_guest on guest_topic_interests(guest_id);
