package com.dailyai.assistant.migration;

import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.testcontainers.containers.PostgreSQLContainer;

import static org.assertj.core.api.Assertions.assertThat;

class GuestFeedbackPostgresMigrationTest {
    @Test
    void migrationsFromV16ToV18PreserveAndCorrectLegacyFeedbackRows() {
        try (PostgreSQLContainer<?> postgres = new PostgreSQLContainer<>("postgres:16-alpine")) {
            postgres.start();
            DriverManagerDataSource dataSource = new DriverManagerDataSource(
                    postgres.getJdbcUrl(), postgres.getUsername(), postgres.getPassword());
            JdbcTemplate jdbc = new JdbcTemplate(dataSource);
            jdbc.execute("create table articles (id bigint primary key)");
            jdbc.execute("create table users (id bigint primary key)");
            jdbc.execute("create table guest_article_interactions (id bigint generated by default as identity primary key, "
                    + "guest_id varchar(36) not null, article_id bigint not null references articles(id) on delete cascade, "
                    + "open_count integer not null default 0, qualified_view_count integer not null default 0, "
                    + "opened_at timestamptz, qualified_viewed_at timestamptz, recommended_at timestamptz, "
                    + "constraint uk_guest_article_interaction unique (guest_id, article_id))");
            jdbc.execute("insert into articles(id) values (1), (2), (3)");
            jdbc.execute("insert into guest_article_interactions(guest_id, article_id) values ('guest1',1),('guest2',2),('guest3',3)");
            jdbc.execute("alter table guest_article_interactions add column useful boolean");
            jdbc.update("update guest_article_interactions set useful = true where guest_id = 'guest1'");
            jdbc.update("update guest_article_interactions set useful = false where guest_id = 'guest2'");

            Flyway.configure().dataSource(dataSource).locations("classpath:db/migration")
                    .baselineOnMigrate(true).baselineVersion("16").load().migrate();

            assertThat(jdbc.queryForMap("select useful, feedback_action from guest_article_interactions where guest_id='guest1'"))
                    .containsEntry("useful", true).containsEntry("feedback_action", "USEFUL");
            assertThat(jdbc.queryForMap("select useful, feedback_action from guest_article_interactions where guest_id='guest2'"))
                    .containsEntry("useful", false).containsEntry("feedback_action", "NOT_USEFUL");
            assertThat(jdbc.queryForMap("select useful, feedback_action from guest_article_interactions where guest_id='guest3'"))
                    .containsEntry("useful", null).containsEntry("feedback_action", null);
            assertThat(jdbc.queryForObject("select count(*) from guest_article_interactions", Integer.class)).isEqualTo(3);
            assertThat(jdbc.queryForObject("select count(*) from guest_article_interactions i join articles a on a.id=i.article_id", Integer.class))
                    .isEqualTo(3);

            // A newly recorded Show me fewer action uses NULL in the legacy Boolean column
            // and remains untouched by the corrective predicate.
            jdbc.update("insert into guest_article_interactions(guest_id, article_id, useful, feedback_action) values ('guest4', 1, null, 'SHOW_ME_FEWER')");
            String correction = "update guest_article_interactions set feedback_action = 'NOT_USEFUL' "
                    + "where useful is false and feedback_action = 'SHOW_ME_FEWER'";
            jdbc.execute(correction);
            jdbc.execute(correction);
            assertThat(jdbc.queryForObject("select feedback_action from guest_article_interactions where guest_id='guest4'", String.class))
                    .isEqualTo("SHOW_ME_FEWER");
        }
    }
}
